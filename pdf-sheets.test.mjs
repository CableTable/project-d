import assert from 'node:assert/strict';
import { pageFields, pageState, pageStates, keepPage, sheetNumbers, dirtySheets, hasChanges, withoutSheet, restoreBalloons } from './web/pdf-sheets.js';
import { createHistory } from './web/edit.js';
import * as BAL from './web/balloons.js';

const d = { pdf: { pages: 4, page: 1 }, raw: { entities: [1], blocks: {} }, hist: createHistory(), dirty: true, titleBlock: { file: 'shared' }, recovery: { rid: 'tab-sheet1' } };
d.hist.push({ entities: [] }, 'Edit');
keepPage(d);
assert.equal(d.pdf.states.size, 1, 'unvisited sheets have no state');
assert.equal(d.pdf.states.get(1).raw, d.raw);
assert.equal(d.pdf.states.get(1).hist.canUndo, true);
assert.equal('titleBlock' in pageFields(d), false, 'title block stays with the tab');
d.pdf.page = 2; d.dirty = false;
assert.equal(pageState(d, 1).recovery, d.recovery, 'an in-flight recovery write follows its kept sheet');
d.recovery = undefined;
assert.equal(pageState(d, 2), d, 'active state comes from the tab');
assert.equal(pageState(d, 3), undefined, 'unvisited pages need no recovery state');
assert.deepEqual(pageStates(d), [d.pdf.states.get(1), d]);
assert.deepEqual(pageStates({ dirty: true }), [{ dirty: true }], 'ordinary tabs keep one copy');
assert.deepEqual(dirtySheets(d), [1]);
assert.equal(hasChanges(d), true, 'a clean active page does not hide another dirty page');
d.dirty = true;
assert.deepEqual(dirtySheets(d), [1, 2]);
assert.deepEqual(sheetNumbers(d.pdf), [1, 2, 3, 4]);
assert.deepEqual(withoutSheet(d.pdf, 2), { sheets: [1, 3, 4], page: 3 });
assert.deepEqual(withoutSheet({ pages: 4, sheets: [1, 3, 4], page: 4 }, 4), { sheets: [1, 3], page: 3 });
assert.deepEqual(withoutSheet(d.pdf, 3), { sheets: [1, 2, 4], page: 2 });
assert.equal(withoutSheet({ pages: 4, sheets: [3], page: 3 }, 3), null);
assert.equal(withoutSheet(d.pdf, 9), null);
const first = d.pdf.states.get(1);
d.raw = { entities: [2], blocks: { other: {} } }; d.hist = createHistory(); d.path = 'sheet-two.dxf';
keepPage(d);
Object.assign(d, pageFields(first));
assert.deepEqual(d.raw.entities, [1]); assert.deepEqual(d.raw.blocks, {});
assert.equal(d.hist.canUndo, true); assert.equal(d.path, undefined, 'another sheet cannot inherit a saved path');
assert.equal(d.recovery.rid, 'tab-sheet1', 'recovery identity returns with its own sheet');
assert.equal(d.pdf.states.get(2).raw.entities[0], 2, 'other drawing stays independent');
const picture = { pdf: { picture: true, page: 1 }, bg: { bitmap: {}, mm: 2, x: 3, y: 4 } };
keepPage(picture);
assert.deepEqual(picture.pdf.states.get(1).bg, { bitmap: null, mm: 2, x: 3, y: 4 }, 'keep calibration without retaining the rendered bitmap');
assert.ok(picture.bg.bitmap, 'capturing state does not mutate the shown background');
const one = BAL.add(BAL.EMPTY, { tip: [0, 0], c: [1, 1], sheet: 1 });
const both = BAL.add(one, { tip: [0, 0], c: [1, 1], sheet: 2 });
const undone = restoreBalloons(both, BAL.EMPTY, 1);
assert.deepEqual(undone.items.map((it) => it.sheet), [2], 'Undo does not erase another sheet');
assert.equal(BAL.add(undone, { tip: [0, 0], c: [1, 1] }).items.at(-1).id, 3, 'IDs stay unique');
assert.deepEqual(restoreBalloons(one, both, 1).items.map((it) => it.sheet), [1], 'Undo cannot resurrect a deleted sheet');
const reset = { ...BAL.update(one, 1, { n: 10 }), next: 3 };
assert.equal(restoreBalloons(one, reset, 1).next, 3, 'Undo restores a next number deliberately below this sheet’s highest number');
console.log('ok PDF sheet state, dirty pages, deletion and balloon Undo');
